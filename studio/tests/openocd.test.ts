import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { ocdArgs, ocdCommands, ocdConfigFile, type OcdOptions } from "../src/lib/openocd/config";

const base: OcdOptions = { port: "/dev/ttyUSB0", speed: "normal", gdbPort: 3333 };

describe("OpenOCD config", () => {
  it("drives the JTAGulator as a Bus Pirate", () => {
    expect(ocdCommands({ ...base, target: "target/stm32f4x.cfg" })).toEqual([
      "adapter driver buspirate",
      "buspirate port /dev/ttyUSB0",
      "buspirate speed normal",
      "transport select jtag",
      "gdb port 3333",
      "source [find target/stm32f4x.cfg]",
    ]);
  });

  it("declares the chain TDI-first when every IR length is known", () => {
    const cmds = ocdCommands({
      ...base,
      taps: [
        { idcode: 0x4ba00477, irLength: 4 },
        { idcode: 0x06413041, irLength: 5 },
      ],
    });
    expect(cmds.filter((c) => c.startsWith("jtag"))).toEqual([
      "jtag newtap chip1 tap -irlen 5 -expected-id 0x06413041",
      "jtag newtap chip0 tap -irlen 4 -expected-id 0x4BA00477",
    ]);
    // Unknown IR length: leave the chain to OpenOCD's auto-probe.
    expect(ocdCommands({ ...base, taps: [{ idcode: 1, irLength: null }] }).some((c) => c.startsWith("jtag"))).toBe(false);
  });

  it("quotes odd port names for Tcl and joins commands for the command line", () => {
    expect(ocdCommands({ ...base, port: "/dev/serial/by-id/usb-FTDI JTAGulator" })[1]).toBe("buspirate port {/dev/serial/by-id/usb-FTDI JTAGulator}");
    expect(ocdArgs(base)).toEqual(["-c", "adapter driver buspirate; buspirate port /dev/ttyUSB0; buspirate speed normal; transport select jtag; gdb port 3333"]);
  });

  it("writes a commented file", () => {
    const f = ocdConfigFile({ ...base, taps: [{ idcode: 0x4ba00477, irLength: null, name: "ARM Cortex-M DAP" }] }, { pins: { tdi: 0, tdo: 1, tck: 2, tms: 3 }, date: new Date("2026-10-19") });
    expect(f).toContain("# OpenOCD configuration generated by JTAGulator Studio on 2026-10-19");
    expect(f).toContain("#   TDI CH0, TDO CH1, TCK CH2, TMS CH3");
    expect(f).toContain("#   1. 0x4BA00477 ARM Cortex-M DAP");
    expect(f).toContain("auto-probe");
  });

  // Set OPENOCD to an openocd binary to check the file with OpenOCD itself: every
  // command must parse; the run then stops when it can't open the (missing) port.
  it.skipIf(!process.env.OPENOCD)("parses in OpenOCD", () => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), "jtag-ocd-"));
    const port = path.join(dir, "no-such-port");
    const cases: OcdOptions[] = [
      { port, speed: "fast", gdbPort: 3333, telnetPort: 4444, target: "target/stm32f4x.cfg" },
      { port, speed: "normal", gdbPort: 3333, taps: [{ idcode: 0x4ba00477, irLength: 4 }, { idcode: null, irLength: 5 }] },
    ];
    for (const o of cases) {
      const file = path.join(dir, "t.cfg");
      fs.writeFileSync(file, ocdConfigFile(o));
      const r = spawnSync(process.env.OPENOCD!, ["-f", file], { encoding: "utf8", timeout: 20000 });
      const out = r.stdout + r.stderr;
      // A bad command is reported as "<file>:<line>: Error: ..."
      expect(out).not.toMatch(/\.cfg:\d+: Error|invalid command name|wrong # args/i);
      expect(out).toContain("Could not open serial port");
    }
    fs.rmSync(dir, { recursive: true });
  });
});
