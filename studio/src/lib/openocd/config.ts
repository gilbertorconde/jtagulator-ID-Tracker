// OpenOCD configuration for the JTAGulator's OpenOCD mode, where the firmware
// acts as a Bus Pirate-compatible JTAG adapter on the pins chosen when the mode
// was entered. The same commands feed the in-app launch and a saved .cfg file.
import type { JtagPins } from "../core/types";

export interface OcdTap {
  /** IDCODE read from the chain, or null for a device in BYPASS. */
  idcode: number | null;
  /** Instruction register length, if known (from a BSDL file). */
  irLength: number | null;
  name?: string;
}

export interface OcdOptions {
  port: string;
  /** Bus Pirate speed: "normal" (~100 kHz) or "fast" (~1 MHz). */
  speed: "normal" | "fast";
  /** A target script from OpenOCD's library, e.g. "target/stm32f4x.cfg". */
  target?: string;
  /** Devices on the chain, nearest TDO first (the order scans report them). */
  taps?: OcdTap[];
  gdbPort?: number;
  telnetPort?: number;
}

const hex8 = (v: number) => "0x" + (v >>> 0).toString(16).toUpperCase().padStart(8, "0");
/** Quote for Tcl: braces keep the text literal. */
const tclWord = (s: string) => (/^[\w./:\\-]+$/.test(s) ? s : `{${s.replace(/[{}]/g, "")}}`);

/** OpenOCD commands, one per line, without comments. */
export function ocdCommands(o: OcdOptions): string[] {
  const out = ["adapter driver buspirate", `buspirate port ${tclWord(o.port)}`, `buspirate speed ${o.speed}`, "transport select jtag"];
  if (o.gdbPort !== undefined) out.push(`gdb port ${o.gdbPort}`);
  if (o.telnetPort !== undefined) out.push(`telnet port ${o.telnetPort}`);
  if (o.target) out.push(`source [find ${o.target}]`);
  else {
    // Declare the chain only when every IR length is known; otherwise let OpenOCD probe it.
    const taps = o.taps ?? [];
    if (taps.length && taps.every((t) => t.irLength)) {
      // OpenOCD lists taps from TDI to TDO, the reverse of the scan order.
      [...taps].reverse().forEach((t, i) => {
        const n = taps.length - 1 - i;
        out.push(`jtag newtap chip${n} tap -irlen ${t.irLength}` + (t.idcode !== null ? ` -expected-id ${hex8(t.idcode)}` : ""));
      });
    }
  }
  return out;
}

/** A complete, commented .cfg file. */
export function ocdConfigFile(o: OcdOptions, about: { pins?: JtagPins; targetName?: string; date?: Date } = {}): string {
  const p = about.pins;
  const head = [
    `# OpenOCD configuration generated by JTAGulator Studio on ${(about.date ?? new Date()).toISOString().slice(0, 10)}`,
    ...(about.targetName ? [`# Target: ${about.targetName}`] : []),
    "#",
    "# The JTAGulator must be in OpenOCD mode first (JTAG menu, O), entered with these pins:",
    p ? `#   TDI CH${p.tdi}, TDO CH${p.tdo}, TCK CH${p.tck}, TMS CH${p.tms}` : "#   (the pinout found by the JTAG scans)",
    "# Then close any serial terminal and run:  openocd -f <this file>",
    "",
  ];
  const taps = o.taps ?? [];
  const chain =
    !o.target && taps.length
      ? [
          "",
          "# Devices found on the chain (nearest TDO first):",
          ...taps.map((t, i) => `#   ${i + 1}. ${t.idcode !== null ? hex8(t.idcode) : "BYPASS"}${t.name ? ` ${t.name}` : ""}${t.irLength ? `, IR ${t.irLength} bits` : ""}`),
          ...(taps.every((t) => t.irLength) ? [] : ["# Some IR lengths are unknown (load a BSDL file), so OpenOCD will auto-probe the chain."]),
        ]
      : [];
  return [...head, ...ocdCommands(o).filter((l) => !l.startsWith("jtag newtap")), ...chain, ...ocdCommands(o).filter((l) => l.startsWith("jtag newtap")), ""].join("\n");
}

/** Command-line arguments for launching OpenOCD with these settings. */
export function ocdArgs(o: OcdOptions): string[] {
  return ["-c", ocdCommands(o).join("; ")];
}
