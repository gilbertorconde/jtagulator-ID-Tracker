// Markdown report of everything known about the target.
import type { Finding } from "./core/types";
import type { TargetProfile } from "./stores/app.svelte";

const ch = (v: number | null | undefined) => (v === null || v === undefined || v < 0 ? "—" : `CH${v}`);

/** One-line Markdown description of a finding. */
export function describeFinding(f: Finding): string {
  switch (f.kind) {
    case "jtag": {
      const pins = `TDI ${ch(f.tdi)}, TDO ${ch(f.tdo)}, TCK ${ch(f.tck)}, TMS ${ch(f.tms)}${f.trst.length ? `, TRST# ${f.trst.map(ch).join("/")}` : ""}`;
      const devs = f.devices.map((d) => `  - Device #${d.index}: \`${d.idcode.hex}\` ${d.idcode.manufacturer ?? "unknown"}${d.idcode.part ? ` (${d.idcode.part})` : ""}`);
      return [`- **JTAG** ${pins}`, ...devs].join("\n");
    }
    case "swd":
      return `- **SWD** SWDIO ${ch(f.swdio)}, SWCLK ${ch(f.swclk)}${f.dpidr ? ` — DPIDR \`${f.dpidr.hex}\` ${f.dpidr.designer ?? ""}${f.dpidr.part ? ` (${f.dpidr.part})` : ""}` : ""}`;
    case "uart":
      return `- **UART** TXD ${ch(f.txd)}, RXD ${ch(f.rxd)} @ ${f.baud}${f.ascii ? ` — reply \`${f.ascii}\`` : ""}`;
    case "uart-txd":
      return `- **UART TXD** ${ch(f.txd)} @ ${f.bestFit ?? "non-standard"} (measured ${f.measuredBaud})`;
    case "rtck":
      return `- **RTCK** TCK ${ch(f.tck)} → RTCK ${ch(f.rtck)}`;
    case "extest":
      return `- **BSR** bit ${f.bit} drives ${ch(f.channel)}`;
    case "irdr":
      return `- **IR** 0x${f.ir.toString(16).toUpperCase()} → DR ${f.dr} bits`;
  }
}

export function markdownReport(t: TargetProfile): string {
  const names = Object.entries(t.channelNames).filter(([, n]) => n);
  return [
    `# ${t.name}`,
    "",
    `Generated by JTAGulator Studio on ${new Date().toLocaleString()}.`,
    "",
    t.notes ? `${t.notes}\n` : "",
    "## Known interfaces",
    "",
    `- Target I/O voltage: ${t.voltage ?? "not set"} V`,
    `- JTAG: TDI ${ch(t.jtag.tdi)}, TDO ${ch(t.jtag.tdo)}, TCK ${ch(t.jtag.tck)}, TMS ${ch(t.jtag.tms)}, TRST# ${ch(t.jtag.trst)}, RTCK ${ch(t.jtag.rtck)}`,
    `- SWD: SWDIO ${ch(t.swd.swdio)}, SWCLK ${ch(t.swd.swclk)}`,
    `- UART: TXD ${ch(t.uart.txd)}, RXD ${ch(t.uart.rxd)}, baud ${t.uart.baud ?? "—"}`,
    "",
    ...(names.length ? ["## Channel labels", "", ...names.map(([k, n]) => `- CH${k}: ${n}`), ""] : []),
    "## Findings",
    "",
    ...(t.findings.length ? t.findings.map((f) => `${describeFinding(f.finding)}  _(${new Date(f.at).toLocaleString()}, ${f.op})_`) : ["None yet."]),
    "",
  ].join("\n");
}
