// Copies the repository's images into public/ (they live in media/ and image/
// for the README) and generates the script API reference from the app's registry.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
for (const dir of ["media", "image"]) {
  const out = path.join(import.meta.dirname, "public", dir);
  fs.mkdirSync(out, { recursive: true });
  for (const f of fs.readdirSync(path.join(root, dir))) fs.copyFileSync(path.join(root, dir, f), path.join(out, f));
}

// Read doc/example/label of every call from studio/src/lib/scripting/api.ts.
const src = fs.readFileSync(path.join(root, "studio/src/lib/scripting/api.ts"), "utf8");
const block = src.slice(src.indexOf("export const CALLS = {"), src.indexOf("} satisfies Record<string, CallSpec>"));
const calls = [...block.matchAll(/^  "([\w.]+)": \{([\s\S]*?)^  \},/gm)].map(([, name, body]) => {
  const str = (k) => body.match(new RegExp(`${k}: (["'\`])((?:\\\\.|(?!\\1).)*)\\1`))?.[2]?.replace(/\\(.)/g, "$1");
  return { name, label: str("label"), doc: str("doc"), example: str("example"), scan: /scan: true/.test(body), risky: str("risky") };
});
if (calls.length < 20) throw new Error(`Only ${calls.length} calls parsed from api.ts`);
const groups = Object.groupBy(calls, (c) => c.name.split(".")[0]);
const titles = { device: "Device", jtag: "JTAG", swd: "SWD", uart: "UART", gpio: "GPIO" };
let md = `<!-- Generated by docs/prepare.mjs from studio/src/lib/scripting/api.ts. Do not edit. -->\n`;
for (const [g, list] of Object.entries(groups)) {
  md += `\n### ${titles[g] ?? g}\n\n| Function | What it does |\n| :--- | :--- |\n`;
  for (const c of list) {
    const sig = `${c.name}(${c.example ?? ""})`.replace(/\|/g, "\\|");
    md += `| \`${sig}\` | ${c.doc.replace(/\|/g, "\\|")}${c.scan ? " Long-running; reports progress." : ""}${c.risky ? ` **Persists:** ${c.risky}` : ""} |\n`;
  }
}
fs.writeFileSync(path.join(import.meta.dirname, "studio/_api-reference.md"), md);
console.log(`prepared images and ${calls.length} API entries`);
